from __future__ import annotations

from pathlib import Path
from typing import Any
from urllib.parse import urlparse
import hashlib
import ipaddress
import json
import shlex
import shutil

from .artifacts import write_json, write_text


BENCHMARK_MANIFEST_BUILD_JSON = "benchmark-manifest-build-report.json"
BENCHMARK_MANIFEST_BUILD_MD = "benchmark-manifest-build-report.md"
_ROLES = ["candidate", "baseline", "ablation"]
_DIRECTIONS = {"higher_is_better", "lower_is_better", "target", "descriptive"}


def build_benchmark_manifest_set(
    *,
    out_dir: Path,
    name: str,
    benchmark_url: str,
    dataset_url: str,
    dataset_version: str,
    split_name: str,
    split_file: Path,
    grader_file: Path,
    grader_version: str,
    license_value: str,
    baseline: str,
    baseline_version: str,
    citation: str,
    metrics: list[str],
    command_template: str = "python3 {grader} --role {role} --metrics {metrics_path}",
    role_commands: dict[str, str] | None = None,
    seed_policy: str = "RESEARCH_AGENT_SEED fixes split/task sampling and stochastic state; RESEARCH_AGENT_REPEAT_INDEX selects repeat.",
    min_repeats: int = 3,
    benchmark_kind: str = "external",
    notes: list[str] | None = None,
    write: bool = True,
    force: bool = False,
) -> dict[str, Any]:
    metric_schema, metric_issues = _parse_metric_specs(metrics)
    split_file = split_file.resolve()
    grader_file = grader_file.resolve()
    split_name_on_disk = split_file.name
    grader_name_on_disk = grader_file.name
    role_commands = role_commands or {}
    blocking = [
        *_required_issues(
            {
                "name": name,
                "benchmark_url": benchmark_url,
                "dataset_url": dataset_url,
                "dataset_version": dataset_version,
                "split_name": split_name,
                "grader_version": grader_version,
                "license": license_value,
                "baseline_version": baseline_version,
                "citation": citation,
                "seed_policy": seed_policy,
            }
        ),
        *metric_issues,
    ]
    if not _external_http_url(dataset_url):
        blocking.append(f"dataset_url 必须是公开 http(s) URL：{dataset_url or 'missing'}")
    if benchmark_url and not _external_http_url(benchmark_url):
        blocking.append(f"benchmark_url 必须是公开 http(s) URL：{benchmark_url}")
    if min_repeats < 3:
        blocking.append(f"min_repeats 至少为 3，当前 {min_repeats}")
    if not split_file.exists() or not split_file.is_file():
        blocking.append(f"split_file 不存在或不是文件：{split_file}")
    if not grader_file.exists() or not grader_file.is_file():
        blocking.append(f"grader_file 不存在或不是文件：{grader_file}")
    if split_name_on_disk == grader_name_on_disk and split_file != grader_file:
        blocking.append(f"split_file 和 grader_file 不能使用相同文件名：{split_name_on_disk}")
    for role in role_commands:
        if role not in _ROLES:
            blocking.append(f"role_command 只能覆盖 candidate、baseline 或 ablation：{role}")
    split_sha256 = _sha256_file(split_file) if split_file.exists() and split_file.is_file() else ""
    grader_sha256 = _sha256_file(grader_file) if grader_file.exists() and grader_file.is_file() else ""
    manifests: list[dict[str, Any]] = []
    for role in _ROLES:
        role_dir = out_dir / role
        metrics_path = f"{role}_metrics.json"
        role_template = role_commands.get(role) or command_template
        command, command_issues = _render_command(role_template, role=role, grader=grader_name_on_disk, metrics_path=metrics_path)
        blocking.extend(command_issues)
        manifest_path = role_dir / "manifest.json"
        manifest = {
            "name": f"{name} {role}",
            "role": role,
            "command": command,
            "metrics_path": metrics_path,
            "expected_artifacts": [metrics_path],
            "expected_metrics": list(metric_schema),
            "metric_schema": metric_schema,
            "benchmark_kind": benchmark_kind,
            "benchmark_url": benchmark_url,
            "dataset_url": dataset_url,
            "dataset_version": dataset_version,
            "split_name": split_name,
            "split_path": split_name_on_disk,
            "split_sha256": split_sha256,
            "license": license_value,
            "baseline": baseline,
            "baseline_version": baseline_version,
            "citation": citation,
            "grader": grader_name_on_disk,
            "grader_path": grader_name_on_disk,
            "grader_version": grader_version,
            "grader_sha256": grader_sha256,
            "seed_policy": seed_policy,
            "min_repeats": min_repeats,
            "source_files": [grader_name_on_disk],
            "notes": [
                *(notes or []),
                "Generated by benchmark-manifest-build; verify method-to-role mapping before execution approval.",
            ],
        }
        manifests.append({"role": role, "path": str(manifest_path), "manifest": manifest})
        if write and not force:
            for target in [manifest_path, role_dir / split_name_on_disk, role_dir / grader_name_on_disk]:
                if target.exists():
                    blocking.append(f"目标文件已存在，使用 --force 覆盖：{target}")
    report = {
        "status": "blocked" if blocking else "ready",
        "out_dir": str(out_dir),
        "manifest_paths": [item["path"] for item in manifests],
        "split_sha256": split_sha256,
        "grader_sha256": grader_sha256,
        "blocking_issues": _unique(blocking),
        "manifests": manifests,
        "next_steps": [
            "人工核对 candidate/baseline/ablation 的命令是否确实运行对应方法。",
            "运行 paper-grade-benchmark-probe 检查 manifest set、URL/DOI 可达性和 hash contract。",
            "把三个 manifest 路径加入 --benchmark-manifest 后再执行 preflight --paper-grade。",
        ],
    }
    if write and report["status"] == "ready":
        _write_manifest_set(out_dir, manifests, split_file, grader_file)
        write_json(out_dir / BENCHMARK_MANIFEST_BUILD_JSON, report)
        write_text(out_dir / BENCHMARK_MANIFEST_BUILD_MD, render_benchmark_manifest_build_markdown(report))
    return report


def render_benchmark_manifest_build_markdown(report: dict[str, Any]) -> str:
    lines = [
        "# Benchmark Manifest Builder",
        "",
        f"- 状态：{report.get('status') or '-'}",
        f"- 输出目录：`{report.get('out_dir') or '-'}`",
        f"- split_sha256：`{report.get('split_sha256') or '-'}`",
        f"- grader_sha256：`{report.get('grader_sha256') or '-'}`",
        "",
        "## Manifest",
        "| Role | Path |",
        "| --- | --- |",
    ]
    manifests = report.get("manifests") if isinstance(report.get("manifests"), list) else []
    for item in manifests:
        if isinstance(item, dict):
            lines.append(f"| {item.get('role') or '-'} | `{item.get('path') or '-'}` |")
    blocking = report.get("blocking_issues") if isinstance(report.get("blocking_issues"), list) else []
    lines.extend(["", "## Blocking Issues"])
    lines.extend(f"- {item}" for item in blocking) if blocking else lines.append("- 无")
    next_steps = report.get("next_steps") if isinstance(report.get("next_steps"), list) else []
    lines.extend(["", "## Next Steps"])
    lines.extend(f"- {item}" for item in next_steps) if next_steps else lines.append("- 无")
    if manifests:
        lines.extend(["", "## Preview"])
        for item in manifests:
            if isinstance(item, dict) and isinstance(item.get("manifest"), dict):
                lines.extend(
                    [
                        f"### {item.get('role') or 'manifest'}",
                        "```json",
                        json.dumps(item["manifest"], ensure_ascii=False, indent=2),
                        "```",
                    ]
                )
    return "\n".join(lines)


def _write_manifest_set(out_dir: Path, manifests: list[dict[str, Any]], split_file: Path, grader_file: Path) -> None:
    for item in manifests:
        path = Path(str(item["path"]))
        role_dir = path.parent
        role_dir.mkdir(parents=True, exist_ok=True)
        shutil.copy2(split_file, role_dir / split_file.name)
        shutil.copy2(grader_file, role_dir / grader_file.name)
        write_json(path, item["manifest"])


def _parse_metric_specs(values: list[str]) -> tuple[dict[str, dict[str, str]], list[str]]:
    schema: dict[str, dict[str, str]] = {}
    issues: list[str] = []
    if not values:
        return {}, ["至少需要一个 --metric name:direction:unit:description"]
    for raw in values:
        parts = str(raw).split(":", 3)
        if len(parts) != 4:
            issues.append(f"metric 格式必须是 name:direction:unit:description：{raw}")
            continue
        name, direction, unit, description = (part.strip() for part in parts)
        if not name:
            issues.append(f"metric name 不能为空：{raw}")
            continue
        if direction not in _DIRECTIONS:
            issues.append(f"{name}: direction 必须是 {', '.join(sorted(_DIRECTIONS))}")
        if not unit:
            issues.append(f"{name}: unit 不能为空")
        if not description:
            issues.append(f"{name}: description 不能为空")
        schema[name] = {"direction": direction, "unit": unit, "description": description}
    return schema, issues


def _render_command(template: str, *, role: str, grader: str, metrics_path: str) -> tuple[list[str], list[str]]:
    try:
        rendered = template.format(role=role, grader=grader, metrics_path=metrics_path)
    except KeyError as exc:
        return [], [f"command_template 使用了未知占位符：{exc}"]
    try:
        command = shlex.split(rendered)
    except ValueError as exc:
        return [], [f"command_template 解析失败：{exc}"]
    if not command:
        return [], ["command_template 生成了空命令"]
    return command, []


def _required_issues(values: dict[str, str]) -> list[str]:
    return [f"{key} 不能为空" for key, value in values.items() if not str(value or "").strip()]


def _external_http_url(value: str) -> bool:
    parsed = urlparse(str(value or "").strip())
    if parsed.scheme not in {"http", "https"} or not parsed.hostname:
        return False
    host = parsed.hostname.lower()
    if "example." in host or host == "localhost" or host.endswith(".localhost") or host.endswith(".local"):
        return False
    try:
        address = ipaddress.ip_address(host)
    except ValueError:
        return True
    return not any([address.is_private, address.is_loopback, address.is_link_local, address.is_multicast, address.is_unspecified])


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _unique(values: list[str]) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []
    for value in values:
        if value in seen:
            continue
        seen.add(value)
        result.append(value)
    return result
